import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.waitForFunction(()=>window.__fireTower?.ready,{timeout:30000});
await page.waitForTimeout(1500);await page.screenshot({path:'test-results/desktop.png',fullPage:true});
await page.locator('[data-light="blue"]').click();await page.waitForTimeout(600);
if(await page.locator('[data-light="blue"]').getAttribute('aria-pressed')!=='true')throw Error('Light preset not applied');
await page.locator('#explore').click();await page.locator('[data-view="stairs"]').click();await page.waitForTimeout(1500);
await page.screenshot({path:'test-results/stairs.png'});
if(!(await page.locator('#explore-panel').isVisible()))throw Error('Explore controls missing');
await page.keyboard.press('Escape');await page.locator('[data-light="golden"]').click();
await page.locator('#motion').click();
if(!(await page.locator('#motion').getAttribute('aria-label')).includes('Resume'))throw Error('Motion pause failed');
const desktop=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,diagnostics:window.__fireTower.diagnostics,canvas:!!document.querySelector('canvas')}));
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1200);await page.screenshot({path:'test-results/mobile.png',fullPage:true});
const mobile=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,scene:window.__fireTower.ready}));
await page.locator('#explore').click();await page.locator('[data-view="cabin"]').click();await page.waitForTimeout(1400);await page.screenshot({path:'test-results/mobile-explore.png'});
console.log(JSON.stringify({desktop,mobile,errors}));
await browser.close();
if(errors.length||desktop.overflow||mobile.overflow)process.exitCode=1;
